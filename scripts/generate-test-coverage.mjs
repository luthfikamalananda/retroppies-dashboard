// Generates docs/test-coverage.md from the Playwright test list (tests/*.spec.ts).
// The list itself (which tests exist, their file/line) is read straight from the
// code via `playwright test --list`, so it can never drift out of sync. Priority
// is not something Playwright knows about — it comes from the `{ tag: '@P0' }`
// etc. written on each `test(...)` call, i.e. still a manual decision, just made
// once at the source instead of copy-pasted into a doc that can go stale.
//
// Run with: npm run test:e2e:coverage-doc

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const outFile = path.resolve(rootDir, 'docs/test-coverage.md');

const PRIORITY_LABELS = {
    P0: 'P0 — critical path, must never break',
    P1: 'P1 — important, breaks a real user flow',
    P2: 'P2 — supporting / nice-to-verify',
    Untagged: 'Untagged — no priority tag set yet',
};
const PRIORITY_ORDER = ['P0', 'P1', 'P2', 'Untagged'];

function listTests() {
    const raw = execFileSync(
        'npx',
        ['playwright', 'test', '--list', '--reporter=json'],
        { cwd: rootDir, encoding: 'utf-8' },
    );
    return JSON.parse(raw);
}

// Playwright nests suites (per file, then per describe block) recursively.
// Walk the tree and flatten every spec into one row, carrying the describe
// titles down as breadcrumbs.
function collectRows(suites, file, breadcrumbs, rows) {
    for (const suite of suites) {
        const nextFile = suite.file ?? file;
        const nextCrumbs = suite.title ? [...breadcrumbs, suite.title] : breadcrumbs;

        for (const spec of suite.specs ?? []) {
            const tag = spec.tags?.find((t) => PRIORITY_ORDER.includes(t)) ?? 'Untagged';
            rows.push({
                priority: tag,
                suite: nextCrumbs.filter((c) => c !== nextFile).join(' › '),
                title: spec.title,
                location: `${nextFile}:${spec.line}`,
            });
        }

        if (suite.suites?.length) {
            collectRows(suite.suites, nextFile, nextCrumbs, rows);
        }
    }
}

function toMarkdown(rows) {
    const generatedAt = new Date().toISOString();
    const lines = [
        '# E2E Test Coverage',
        '',
        `> Auto-generated by \`npm run test:e2e:coverage-doc\` from \`tests/*.spec.ts\` — do not edit by hand, it will be overwritten. Last generated: ${generatedAt}.`,
        '',
        'Priority comes from the `{ tag: \'@P0\' | \'@P1\' | \'@P2\' }` set on each `test(...)` in code. To change a priority, edit the tag in the test file and re-run the generator — not this file.',
        '',
    ];

    for (const priority of PRIORITY_ORDER) {
        const group = rows.filter((r) => r.priority === priority);
        if (group.length === 0) continue;

        lines.push(`## ${PRIORITY_LABELS[priority]}`, '');
        lines.push('| Suite | Test | Location |', '|---|---|---|');
        for (const row of group) {
            lines.push(`| ${row.suite || '—'} | ${row.title} | \`${row.location}\` |`);
        }
        lines.push('');
    }

    lines.push(`Total tests: ${rows.length}.`, '');
    return lines.join('\n');
}

const data = listTests();
const rows = [];
for (const suite of data.suites) {
    collectRows([suite], suite.file, [], rows);
}

writeFileSync(outFile, toMarkdown(rows));
console.log(`Wrote ${rows.length} test(s) to ${path.relative(rootDir, outFile)}`);
